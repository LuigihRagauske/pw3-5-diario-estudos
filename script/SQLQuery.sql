CREATE TABLE TAREFA (
    ID_TAREFA BIGINT IDENTITY(1,1) NOT NULL,
    TITULO VARCHAR(50) NOT NULL,
    MATERIA VARCHAR(50),
    DATA_ENTREGA DATETIME2(6),
    
    -- Enum simulado com CHECK (Status por texto)
    STATUS_TAREFA VARCHAR(20) NOT NULL 
        CONSTRAINT CK_TAREFA_STATUS 
        CHECK (STATUS_TAREFA IN ('Pendente', 'Em Andamento', 'Concluída')),
        
    -- Enum simulado com CHECK (Prioridade por: Baixa, Média, Alta)
    PRIORIDADE TINYINT NOT NULL 
        CONSTRAINT CK_TAREFA_PRIORIDADE 
        CHECK (PRIORIDADE IN ('BAIXA', 'MEDIA', 'ALTA')),

    -- Definição da Chave Primária
    CONSTRAINT PK_TAREFA PRIMARY KEY (ID_TAREFA)
);
